import { Router } from "express";
import { z } from "zod";
import { anthropic } from "@workspace/integrations-anthropic-ai";
import { getStaticPreamble, buildDynamicSuffix } from "../lib/systemPrompt";
import { inferProfile } from "../lib/profile";
import { recordError } from "../lib/alerting";
import { Redis } from "@upstash/redis";

const router = Router();

// ---------------------------------------------------------------------------
// Upstash Redis (optional) — in-memory fallback when not configured
// ---------------------------------------------------------------------------
let redis: Redis | null = null;
try {
  if (
    process.env.UPSTASH_REDIS_REST_URL &&
    process.env.UPSTASH_REDIS_REST_TOKEN
  ) {
    redis = new Redis({
      url: process.env.UPSTASH_REDIS_REST_URL,
      token: process.env.UPSTASH_REDIS_REST_TOKEN,
    });
  }
} catch {
  // Redis not configured — in-memory fallback active
}

const rateLimitMap = new Map<string, { count: number; resetAt: number }>();
const RATE_LIMIT_MAX = 30;
const RATE_LIMIT_WINDOW_S = 3600;

async function checkRateLimit(
  ip: string,
): Promise<{ allowed: boolean; remaining: number }> {
  const key = `miaw:rl:${ip}`;

  if (redis) {
    try {
      const count = await redis.incr(key);
      if (count === 1) {
        await redis.expire(key, RATE_LIMIT_WINDOW_S);
      }
      const allowed = count <= RATE_LIMIT_MAX;
      return { allowed, remaining: Math.max(0, RATE_LIMIT_MAX - count) };
    } catch (err) {
      void err; // Fall through to in-memory on Redis failure
    }
  }

  const now = Date.now();
  const record = rateLimitMap.get(ip);
  if (!record || now > record.resetAt) {
    rateLimitMap.set(ip, {
      count: 1,
      resetAt: now + RATE_LIMIT_WINDOW_S * 1000,
    });
    return { allowed: true, remaining: RATE_LIMIT_MAX - 1 };
  }
  if (record.count >= RATE_LIMIT_MAX) {
    return { allowed: false, remaining: 0 };
  }
  record.count += 1;
  return { allowed: true, remaining: RATE_LIMIT_MAX - record.count };
}

// ---------------------------------------------------------------------------
// Request schema — validated before any business logic runs
// ---------------------------------------------------------------------------
const MessageSchema = z.object({
  role: z.enum(["user", "assistant"]),
  content: z.string().max(8000),
});

const VisitorProfileSchema = z.object({
  type: z.enum([
    "architect",
    "engineer",
    "researcher",
    "developer",
    "student",
    "urban_planner",
    "unknown",
  ]),
  context: z.string().max(500),
  identified: z.boolean(),
  identifiedAtTurn: z.number().int().nullable(),
});

const ChatRequestSchema = z.object({
  messages: z.array(MessageSchema).max(50),
  profile: VisitorProfileSchema.optional().default({
    type: "unknown",
    context: "",
    identified: false,
    identifiedAtTurn: null,
  }),
  turnCount: z.number().int().min(0).max(30).optional().default(0),
  // P3-D: Opt-in session context for returning visitors.
  // A 100–150 word plain-text summary of the previous visit, generated by
  // /api/sessions. Injected as an additional system block between the cached
  // static preamble and the per-request dynamic suffix.
  sessionContext: z.string().max(1200).optional(),
  // P3-C: Visitor's detected language — ISO 639-1 code (e.g. "es", "pt", "fr").
  // Detected client-side from the visitor's messages and passed through here
  // so the dynamic suffix can inject the appropriate in-language reinforcement.
  // Optional: absence means English or undetermined — no extra block is added.
  detectedLanguage: z.string().max(10).optional(),
});

// ---------------------------------------------------------------------------
// Warm the static preamble at module load so the first real request
// does not pay the disk-read cost. Cache eligibility also starts earlier.
// ---------------------------------------------------------------------------
getStaticPreamble();

// ---------------------------------------------------------------------------
// POST /api/chat
// ---------------------------------------------------------------------------
router.post("/chat", async (req, res) => {
  const ip =
    (req.headers["x-forwarded-for"] as string)?.split(",")[0].trim() ||
    req.socket.remoteAddress ||
    "127.0.0.1";

  const { allowed } = await checkRateLimit(ip);
  if (!allowed) {
    res.status(429).json({
      error: "rate_limit",
      message: "You've had a good conversation. Come back in an hour.",
    });
    return;
  }

  const parsed = ChatRequestSchema.safeParse(req.body);
  if (!parsed.success) {
    res.status(400).json({
      error: "invalid_request",
      details: parsed.error.flatten(),
    });
    return;
  }

  const { messages, profile, turnCount, sessionContext, detectedLanguage } = parsed.data;

  const updatedProfile = inferProfile(messages, profile, turnCount);

  // Send streaming headers immediately so the browser can open the connection
  // before Claude produces its first token. Reduces perceived TTFT.
  res.setHeader("Content-Type", "text/plain; charset=utf-8");
  res.setHeader("Transfer-Encoding", "chunked");
  res.setHeader("Cache-Control", "no-store");
  res.setHeader("X-Accel-Buffering", "no");
  res.flushHeaders();

  // Disable TCP Nagle's algorithm so each res.write() is sent as its own
  // TCP segment immediately — prevents small token chunks from being batched
  // into a single packet (which creates the "chunky" streaming appearance).
  req.socket?.setNoDelay(true);

  // ---------------------------------------------------------------------------
  // System prompt — two or three-block structure for Anthropic prompt caching.
  //
  // Block 1 (static, cache_control: ephemeral):
  //   Agent identity + tone rules + hard rules + full knowledge base.
  //   ~5300 tokens. Anthropic caches this block for 5 minutes; subsequent
  //   requests reuse the cache and skip re-processing entirely, cutting
  //   time-to-first-token by ~85% on cache hits.
  //
  // Block 2 (optional, dynamic — P3-D returning visitor):
  //   100–150 word summary of the visitor's previous session generated by
  //   POST /api/sessions. Only present when the client sends `sessionContext`.
  //   Not cached (unique per visitor).
  //
  // Block 3 (dynamic, no cache):
  //   Visitor profile + conversation phase + current turn number.
  //   ~150 tokens. Unique per request — cannot be cached.
  // ---------------------------------------------------------------------------
  const systemBlocks: Array<{
    type: "text";
    text: string;
    cache_control?: { type: "ephemeral" };
  }> = [
    {
      type: "text",
      text: getStaticPreamble(),
      cache_control: { type: "ephemeral" },
    },
  ];

  if (sessionContext) {
    systemBlocks.push({
      type: "text",
      text: `RETURNING VISITOR — previous session context:\n${sessionContext}\n\nGreet them as someone you already know without being overly familiar. Do not ask questions you already know the answer to from this context.`,
    });
  }

  // P3-C: Pass the client-detected language into the dynamic suffix so the
  // appropriate in-language reinforcement block is injected when a non-English
  // language is confirmed. No-op when undefined (English or undetermined).
  systemBlocks.push({
    type: "text",
    text: buildDynamicSuffix(updatedProfile, turnCount, detectedLanguage),
  });

  const claudeMessages =
    messages.length === 0
      ? [{ role: "user" as const, content: "begin" }]
      : messages
          .filter((m) => m.role === "user" || m.role === "assistant")
          .map((m) => ({
            role: m.role as "user" | "assistant",
            content: m.content,
          }));

  try {
    const stream = anthropic.messages.stream({
      model: "claude-sonnet-4-6",
      // 1024 tokens aligns with the agent's ≤90-word conversational rule while
      // still allowing ~750 words for genuine deep-technical questions.
      // Previously 8192 — over-provisioned for this use case by 8×.
      max_tokens: 1024,
      system: systemBlocks,
      messages: claudeMessages,
    });

    for await (const chunk of stream) {
      if (
        chunk.type === "content_block_delta" &&
        chunk.delta.type === "text_delta"
      ) {
        res.write(chunk.delta.text);
      }
    }

    res.end();
  } catch (err) {
    req.log.error({ err }, "Claude streaming error");
    recordError("claude");
    if (!res.headersSent) {
      res.status(500).json({ error: "stream_error" });
    } else {
      res.end();
    }
  }
});

export default router;
